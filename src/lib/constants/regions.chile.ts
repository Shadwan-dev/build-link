// ✅ Funciones auxiliares
export const getRegionById = (id: string) => REGIONS_CHILE.find((r) => r.id === id);
export const getProvincesByRegion = (regionId: string) =>
  PROVINCES_CHILE.filter((p) => p.regionId === regionId);
export const getProvinceById = (id: string) => PROVINCES_CHILE.find((p) => p.id === id);
export const getRegionByProvinceId = (provinceId: string) => {
  const province = getProvinceById(provinceId);
  return province ? getRegionById(province.regionId) : undefined;
};
